-- ----------------------------------------------------------------------------
-- TLGD_TORNEO (TOR) · estados: P próximo · B inscripción abierta · C cerrada
--                     J en juego · T terminado · A anulado
-- ----------------------------------------------------------------------------
IF OBJECT_ID(N'dbo.TLGD_TORNEO', N'U') IS NULL
CREATE TABLE dbo.TLGD_TORNEO (
    CTOR_ID_TORNEO               INT IDENTITY(1,1) NOT NULL,
    CTOR_CODIGO                  VARCHAR(20)   NOT NULL,
    STOR_NOMBRE                  VARCHAR(100)  NOT NULL,
    CTOR_COD_TIPO                VARCHAR(3)    NOT NULL,   -- TIPO_TORNEO: SAT / BAT / INT
    CTOR_ID_TORNEO_DESTINO       INT           NULL,       -- International del mes al que clasifica (SAT/BAT)
    NTOR_MAX_EQUIPOS             INT           NOT NULL,
    NTOR_COSTO_INSCRIPCION       DECIMAL(10,2) NOT NULL,
    NTOR_PREMIO_EFECTIVO         DECIMAL(10,2) NOT NULL CONSTRAINT DF_TOR_PREMIO DEFAULT (0),
    NTOR_APORTE_POZO             DECIMAL(10,2) NOT NULL CONSTRAINT DF_TOR_APORTE DEFAULT (0),
    NTOR_POZO_GARANTIZADO        DECIMAL(10,2) NOT NULL CONSTRAINT DF_TOR_POZO_GAR DEFAULT (0),
    NTOR_POZO_ACUMULADO          DECIMAL(10,2) NOT NULL CONSTRAINT DF_TOR_POZO_ACU DEFAULT (0),
    DTOR_FEC_CIERRE_INSCRIPCION  DATETIME2(0)  NOT NULL,
    DTOR_FEC_INICIO              DATETIME2(0)  NOT NULL,
    FTOR_ESTADO                  CHAR(1)       NOT NULL CONSTRAINT DF_TOR_ESTADO DEFAULT ('P'),
    AUD_INS_FEC                  DATETIME2(0)  NOT NULL CONSTRAINT DF_TOR_AUD_INS_FEC DEFAULT (CONVERT(DATETIME2(0), SYSDATETIMEOFFSET() AT TIME ZONE 'SA Pacific Standard Time')),
    AUD_INS_USER                 VARCHAR(50)   NOT NULL,
    AUD_UPD_FEC                  DATETIME2(0)  NULL,
    AUD_UPD_USER                 VARCHAR(50)   NULL,
    CONSTRAINT PK_TLGD_TORNEO PRIMARY KEY (CTOR_ID_TORNEO),
    CONSTRAINT UQ_TOR_CODIGO UNIQUE (CTOR_CODIGO),
    CONSTRAINT FK_TOR_DESTINO FOREIGN KEY (CTOR_ID_TORNEO_DESTINO) REFERENCES dbo.TLGD_TORNEO (CTOR_ID_TORNEO),
    CONSTRAINT CK_TOR_TIPO CHECK (CTOR_COD_TIPO IN ('SAT', 'BAT', 'INT')),
    CONSTRAINT CK_TOR_ESTADO CHECK (FTOR_ESTADO IN ('P', 'B', 'C', 'J', 'T', 'A', 'V', 'I')),
    CONSTRAINT CK_TOR_FECHAS CHECK (DTOR_FEC_CIERRE_INSCRIPCION <= DTOR_FEC_INICIO),
    CONSTRAINT CK_TOR_MONTOS CHECK (NTOR_COSTO_INSCRIPCION >= 0 AND NTOR_PREMIO_EFECTIVO >= 0 AND NTOR_APORTE_POZO >= 0
                                    AND NTOR_POZO_GARANTIZADO >= 0 AND NTOR_POZO_ACUMULADO >= 0)
);
GO

-- ----------------------------------------------------------------------------
-- TLGD_INSCRIPCION (INS) · estados: P pendiente de pago · C confirmada · D descalificada · A anulada
-- Sin tabla de cupos: los clasificados se inscriben solos (método CUPO).
-- ----------------------------------------------------------------------------
IF OBJECT_ID(N'dbo.TLGD_INSCRIPCION', N'U') IS NULL
CREATE TABLE dbo.TLGD_INSCRIPCION (
    CINS_ID_INSCRIPCION    INT IDENTITY(1,1) NOT NULL,
    CTOR_ID_TORNEO         INT          NOT NULL,
    CEQU_ID_EQUIPO         INT          NOT NULL,
    CINS_COD_METODO        VARCHAR(10)  NOT NULL,          -- METODO_INSCRIPCION: PAGO / CUPO
    CTOR_ID_TORNEO_ORIGEN  INT          NULL,              -- si es CUPO: torneo donde clasificó
    NINS_SEMILLA           INT          NULL,
    FINS_ESTADO            CHAR(1)      NOT NULL CONSTRAINT DF_INS_ESTADO DEFAULT ('P'),
    AUD_INS_FEC            DATETIME2(0) NOT NULL CONSTRAINT DF_INS_AUD_INS_FEC DEFAULT (CONVERT(DATETIME2(0), SYSDATETIMEOFFSET() AT TIME ZONE 'SA Pacific Standard Time')),
    AUD_INS_USER           VARCHAR(50)  NOT NULL,
    AUD_UPD_FEC            DATETIME2(0) NULL,
    AUD_UPD_USER           VARCHAR(50)  NULL,
    CONSTRAINT PK_TLGD_INSCRIPCION PRIMARY KEY (CINS_ID_INSCRIPCION),
    CONSTRAINT FK_INS_TORNEO FOREIGN KEY (CTOR_ID_TORNEO) REFERENCES dbo.TLGD_TORNEO (CTOR_ID_TORNEO),
    CONSTRAINT FK_INS_EQUIPO FOREIGN KEY (CEQU_ID_EQUIPO) REFERENCES dbo.TLGD_EQUIPO (CEQU_ID_EQUIPO),
    CONSTRAINT FK_INS_TORNEO_ORIGEN FOREIGN KEY (CTOR_ID_TORNEO_ORIGEN) REFERENCES dbo.TLGD_TORNEO (CTOR_ID_TORNEO),
    CONSTRAINT CK_INS_METODO CHECK (CINS_COD_METODO IN ('PAGO', 'CUPO')),
    CONSTRAINT CK_INS_ORIGEN CHECK (CINS_COD_METODO = 'PAGO' OR CTOR_ID_TORNEO_ORIGEN IS NOT NULL),
    CONSTRAINT CK_INS_ESTADO CHECK (FINS_ESTADO IN ('P', 'C', 'D', 'A', 'V', 'I'))
);
GO
-- Un equipo se inscribe una sola vez por torneo (las anuladas no cuentan)
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'UX_INS_TORNEO_EQUIPO')
    CREATE UNIQUE INDEX UX_INS_TORNEO_EQUIPO ON dbo.TLGD_INSCRIPCION (CTOR_ID_TORNEO, CEQU_ID_EQUIPO) WHERE FINS_ESTADO <> 'A';
GO

-- ----------------------------------------------------------------------------
